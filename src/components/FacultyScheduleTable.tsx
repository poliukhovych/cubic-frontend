          const oppositeParity: Parity = targetLesson.parity === "odd" ? "even" : "odd";
          next[srcIdx] = {
            ...movingLesson,
            weekday: to.weekday,
            pair: to.pair,
            group: to.group,
            time: timeOf(to.pair),
            parity: oppositeParity,
          };
